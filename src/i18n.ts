const dicts: Record<Lang, Dict> = { fr, en, ar };

export function t(key: string, lang: Lang, ...args: string[]): string {
  const val = dicts[lang]?.[key];
  if (!val) return key;
  if (typeof val === 'function') return val(...args);
  return val;
}

